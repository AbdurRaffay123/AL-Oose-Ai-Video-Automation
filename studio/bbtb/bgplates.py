"""Background plates cropped from the originals (book spreads, environment art) -> library/backgrounds/.

A scene in library/backgrounds.yaml may name a `parent` asset and a `crop` box instead of using a whole
asset. `bbtb plates` cuts that box out of the original (pixels only cropped, never painted), saves it as
library/backgrounds/<SCENE>.png and records parent, parent hash, box and file hash in
library/backgrounds/manifest.yaml. keyframes.plate() then reads the saved file.

`pdf_page: N` (2026-10-05): the parent is the story PDF and the box is in page-N pixels. The page's embedded painting
is extracted as-is with pdfimages (300 ppi, art only: the verse is a separate text layer, so it is NOT in the plate)
and cached in library/derived/book_pages/. Adobe CMYK JPEGs are stored inverted, so they are inverted back first.
"""
from __future__ import annotations

import hashlib
import subprocess
import tempfile
from pathlib import Path

import yaml
from PIL import Image

from . import registry
from .paths import DERIVED, LIBRARY, rel

Image.MAX_IMAGE_PIXELS = None
DIR = LIBRARY / "backgrounds"
MANIFEST = DIR / "manifest.yaml"


def specs() -> dict:
    return yaml.safe_load((LIBRARY / "backgrounds.yaml").read_text())


def book_page(pdf_id: str, page: int) -> Image.Image:
    """The painting embedded in one PDF page (cached). Read-only on the original."""
    cache = DERIVED / "book_pages" / f"page{page:02d}.png"
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run(["pdfimages", "-f", str(page), "-l", str(page), "-j", str(registry.path_of(pdf_id)),
                            str(Path(tmp) / "img")], check=True)
            found = sorted(Path(tmp).glob("img-*"), key=lambda p: -p.stat().st_size)
            if not found:
                raise ValueError(f"page {page} of {pdf_id} has no embedded image")
            im = Image.open(found[0])
            rgb = im.point(lambda v: 255 - v).convert("RGB") if im.mode == "CMYK" else im.convert("RGB")
            rgb.save(cache)
    return Image.open(cache).convert("RGB")


def build(only: str | None = None) -> list[dict]:
    assets = registry.load()
    manifest = yaml.safe_load(MANIFEST.read_text()) if MANIFEST.exists() else {}
    manifest = manifest or {}
    done = []
    for scene, spec in specs().items():
        if "crop" not in spec or (only and not scene.startswith(only)):
            continue
        src = (book_page(spec["parent"], spec["pdf_page"]) if spec.get("pdf_page")
               else Image.open(registry.path_of(spec["parent"])).convert("RGB"))
        x0, y0, x1, y1 = spec["crop"]
        if not (0 <= x0 < x1 <= src.width and 0 <= y0 < y1 <= src.height):
            raise ValueError(f"{scene}: crop {spec['crop']} is outside {spec['parent']} ({src.width}x{src.height})")
        out = LIBRARY / spec["file"]
        out.parent.mkdir(parents=True, exist_ok=True)
        src.crop((x0, y0, x1, y1)).save(out)
        manifest[scene] = {"file": rel(out), "parent": spec["parent"], "parent_sha256": assets[spec["parent"]]["sha256"],
                           **({"pdf_page": spec["pdf_page"]} if spec.get("pdf_page") else {}),
                           "crop": spec["crop"], "size": [x1 - x0, y1 - y0],
                           "sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
                           "method": "bgplates.build (crop only, no painting)"}
        done.append({"scene": scene, "size": (x1 - x0, y1 - y0), "file": rel(out)})
    DIR.mkdir(parents=True, exist_ok=True)
    with open(MANIFEST, "w") as f:
        f.write("# GENERATED by `bbtb plates`: background plates cropped from originals (never painted).\n")
        yaml.safe_dump(manifest, f, sort_keys=True)
    return done
