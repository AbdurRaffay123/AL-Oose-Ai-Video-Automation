"""Asset registry: stable IDs + SHA-256 for every original file.

Originals are never modified. `build()` writes library/assets.yaml;
`verify()` re-hashes and reports anything changed, missing or new.
Curated provenance notes live separately in library/asset_notes.yaml so
regenerating hashes never loses them.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
from pathlib import Path

import yaml
from PIL import Image

from .paths import ASSET_NOTES_YAML, ASSETS_YAML, ORIGINALS, rel

Image.MAX_IMAGE_PIXELS = None

IMAGE_EXT = {".png", ".jpg", ".jpeg", ".webp"}
AUDIO_EXT = {".wav", ".mp3", ".m4a"}
VIDEO_EXT = {".mp4", ".mov"}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def slug(path: Path) -> str:
    """Stable ID from the path relative to ORIGINALS, e.g. images.sheets.landing-sheet-v-777."""
    parts = path.relative_to(ORIGINALS).with_suffix("").parts
    clean = [re.sub(r"[^a-z0-9]+", "-", p.lower()).strip("-") for p in parts]
    return ".".join(clean)


def real_kind(path: Path) -> str:
    with open(path, "rb") as f:
        magic = f.read(4)
    if magic == b"8BPS":
        return "psd"  # e.g. "1. GREEN GRASS.jpg" is really a layered Photoshop file
    ext = path.suffix.lower()
    if ext in IMAGE_EXT:
        return "image"
    if ext in AUDIO_EXT:
        return "audio"
    if ext in VIDEO_EXT:
        return "video"
    if ext == ".pdf":
        return "pdf"
    return "other"


def probe_duration(path: Path) -> float | None:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", str(path)],
        capture_output=True, text=True,
    )
    try:
        return round(float(json.loads(out.stdout)["format"]["duration"]), 3)
    except (KeyError, ValueError, json.JSONDecodeError):
        return None


def describe(path: Path) -> dict:
    kind = real_kind(path)
    entry = {"path": rel(path), "kind": kind, "bytes": path.stat().st_size, "sha256": sha256(path)}
    if kind in ("image", "psd"):
        with Image.open(path) as im:
            entry["size"] = [im.width, im.height]
            entry["alpha"] = im.mode in ("RGBA", "LA") or "transparency" in im.info
    elif kind in ("audio", "video"):
        entry["duration"] = probe_duration(path)
    return entry


def originals() -> list[Path]:
    return sorted(p for p in ORIGINALS.rglob("*") if p.is_file() and p.name != ".DS_Store")


def build() -> dict:
    assets = {slug(p): describe(p) for p in originals()}
    ASSETS_YAML.parent.mkdir(parents=True, exist_ok=True)
    with open(ASSETS_YAML, "w") as f:
        f.write("# GENERATED by `bbtb audit --rebuild`. Do not edit; curate notes in asset_notes.yaml.\n")
        yaml.safe_dump({"assets": assets}, f, sort_keys=True, allow_unicode=True)
    return assets


def load() -> dict:
    with open(ASSETS_YAML) as f:
        return yaml.safe_load(f)["assets"]


def notes() -> dict:
    if not ASSET_NOTES_YAML.exists():
        return {}
    with open(ASSET_NOTES_YAML) as f:
        return yaml.safe_load(f) or {}


def path_of(asset_id: str) -> Path:
    from .paths import ROOT
    return ROOT / load()[asset_id]["path"]


def verify() -> dict:
    """Return {'changed': [...], 'missing': [...], 'new': [...]} (empty lists = all good)."""
    known = load()
    current = {slug(p): p for p in originals()}
    report = {"changed": [], "missing": [], "new": []}
    for aid, meta in known.items():
        p = current.get(aid)
        if p is None:
            report["missing"].append(aid)
        elif p.stat().st_size != meta["bytes"] or sha256(p) != meta["sha256"]:
            report["changed"].append(aid)
    report["new"] = sorted(set(current) - set(known))
    return report
