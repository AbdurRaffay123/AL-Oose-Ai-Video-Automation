"""Jason's music library (owner 2026-10-05): drop tracks into library/audio/music/jason/, run `bbtb music` (free).

Each track is measured locally (ffmpeg decode + numpy): duration, loudness, tempo (onset autocorrelation) and
brightness (spectral centroid). Mood / energy / best-for are ESTIMATES from those numbers (rules below), written to
MUSIC_INVENTORY.md + music_inventory.yaml; edit the YAML to correct a label - a hand edit (`checked: true`) is kept.

A script with `music: auto` (or `music: auto:<mood>`) picks the best track for the episode mood (default playful),
never the track the previous episode used (`last_used` in music_inventory.yaml).
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import numpy as np
import yaml

from .paths import LIBRARY

DIR = LIBRARY / "audio" / "music" / "jason"
INV = DIR / "music_inventory.yaml"
EXTS = (".mp3", ".wav", ".m4a", ".aac", ".ogg", ".flac")
SR = 22050


def _pcm(path: Path) -> np.ndarray:
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32)


def analyse(path: Path) -> dict:
    x = _pcm(path)
    dur = len(x) / SR
    rms_db = float(20 * np.log10(np.sqrt(np.mean(x ** 2)) + 1e-9))
    hop, win = 512, 1024
    frames = np.lib.stride_tricks.sliding_window_view(x, win)[::hop] if len(x) > win else np.zeros((1, win))
    spec = np.abs(np.fft.rfft(frames * np.hanning(win), axis=1))
    freqs = np.fft.rfftfreq(win, 1 / SR)
    centroid = float((spec * freqs).sum() / (spec.sum() + 1e-9))
    flux = np.maximum(np.diff(spec, axis=0), 0).sum(axis=1)                 # onset strength
    bpm = 0.0
    if len(flux) > 64:
        f = flux - flux.mean()
        ac = np.correlate(f, f, "full")[len(f) - 1:]
        fps = SR / hop
        lo, hi = int(fps * 60 / 180), int(fps * 60 / 60)                     # 60-180 bpm
        if hi < len(ac):
            lag = lo + int(np.argmax(ac[lo:hi]))
            bpm = round(60 * fps / lag, 1)
    energy = "high" if rms_db > -16 or bpm >= 130 else "low" if rms_db < -26 or bpm < 85 else "medium"
    bright = centroid > 2200
    mood = ("playful" if bright and bpm >= 100 else "adventurous" if energy == "high" else
            "tense" if not bright and bpm >= 90 else "emotional" if energy == "low" else "funny" if bright else "playful")
    best = {"high": ["opening", "action"], "medium": ["dialogue", "CTA"], "low": ["dialogue", "ending"]}[energy]
    return {"file": path.name, "duration": round(dur, 2), "loudness_db": round(rms_db, 1), "tempo_bpm": bpm,
            "brightness_hz": round(centroid), "energy": energy, "mood": mood, "best_for": best, "checked": False}


def scan() -> dict:
    """Analyse new/changed tracks; keep hand-checked labels. Writes the YAML + MUSIC_INVENTORY.md."""
    DIR.mkdir(parents=True, exist_ok=True)
    inv = yaml.safe_load(INV.read_text()) if INV.exists() else {}
    inv = inv or {}
    tracks = inv.get("tracks", {})
    files = sorted(p for p in DIR.iterdir() if p.suffix.lower() in EXTS)
    for p in files:
        old = tracks.get(p.name)
        if old and old.get("checked") and old.get("bytes") == p.stat().st_size:
            continue
        tracks[p.name] = {**analyse(p), "bytes": p.stat().st_size}
    tracks = {k: v for k, v in tracks.items() if (DIR / k).exists()}
    inv["tracks"] = tracks
    INV.write_text("# GENERATED by `bbtb music` (labels are estimates; set checked: true after correcting one).\n"
                   + yaml.safe_dump(inv, sort_keys=True, allow_unicode=True))
    _markdown(inv)
    return inv


def _markdown(inv: dict) -> None:
    rows = [f"| `{k}` | {v['duration']:.1f}s | {v['mood']} | {v['energy']} | {', '.join(v['best_for'])} | "
            f"{v['tempo_bpm']:g} | {v['loudness_db']} dB | {'yes' if v.get('checked') else 'estimate'} |"
            for k, v in sorted(inv.get("tracks", {}).items())]
    body = "\n".join(rows) if rows else "| (no tracks yet: drop Jason's files into this folder and run `./bbtb music`) |||||||"
    (DIR / "MUSIC_INVENTORY.md").write_text(f"""# Jason's music library
Drop tracks (mp3/wav/m4a/aac/ogg/flac) here, then run `./bbtb music` (free, local).
- **Labels:** mood, energy and best-for are estimated from tempo, loudness and brightness. Correct them in
  `music_inventory.yaml` and set `checked: true`, and the edit is kept.
- **In a script:** `music: auto` (or `music: auto:<mood>`) picks the best track for the episode, never the one the
  previous episode used (`last_used`: {inv.get('last_used') or '-'}).

| File | Duration | Mood | Energy | Best for | Tempo (bpm) | Loudness | Labels |
|---|---|---|---|---|---|---|---|
{body}
""")


def pick(mood: str, seconds: float, record: bool = False) -> Path | None:
    """Best track for `mood` (exact mood first, then playful/funny for comedy), long enough if possible, never the
    previous episode's track. None when the library is empty (the caller falls back to the cached bed)."""
    inv = scan() if not INV.exists() else (yaml.safe_load(INV.read_text()) or {})
    tracks = {k: v for k, v in inv.get("tracks", {}).items() if (DIR / k).exists()}
    if not tracks:
        return None
    last = inv.get("last_used")
    fam = {"funny": ["funny", "playful"], "playful": ["playful", "funny"], "tense": ["tense"],
           "adventurous": ["adventurous", "playful"], "emotional": ["emotional"]}.get(mood, [mood])

    def score(item):
        k, v = item
        return (k == last, -(3 - fam.index(v["mood"])) if v["mood"] in fam else 0, v["duration"] < seconds, -v["duration"])
    name = sorted(tracks.items(), key=score)[0][0]
    if record:
        inv["last_used"] = name
        INV.write_text("# GENERATED by `bbtb music` (labels are estimates; set checked: true after correcting one).\n"
                       + yaml.safe_dump(inv, sort_keys=True, allow_unicode=True))
        _markdown(inv)
    return DIR / name
